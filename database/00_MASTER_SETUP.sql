-- ---- PKG_CP_CHEQUE (backend/src/handlers/cheque.handler.ts) ----
-- Emitir, cobrar y anular un cheque mueven tambien su contrasena de pago
-- (y el saldo de la factura) via PKG_CP_CONTRASENA_PAGO.
CREATE OR REPLACE PACKAGE PKG_CP_CHEQUE AS
    PROCEDURE SP_LISTAR_CHEQUES(p_cursor OUT SYS_REFCURSOR);
    PROCEDURE SP_OBTENER_CHEQUE(p_id_cheque IN NUMBER, p_cursor OUT SYS_REFCURSOR);
    PROCEDURE SP_INSERTAR_CHEQUE(
        p_id_contrasena_pago IN NUMBER,
        p_banco IN VARCHAR2,
        p_numero_cheque IN VARCHAR2,
        p_fecha_emision IN DATE,
        p_id_cheque_out OUT NUMBER
    );
    PROCEDURE SP_ACTUALIZAR_CHEQUE(
        p_id_cheque IN NUMBER,
        p_banco IN VARCHAR2,
        p_numero_cheque IN VARCHAR2,
        p_fecha_emision IN DATE
    );
    PROCEDURE SP_COBRAR_CHEQUE(
        p_id_cheque IN NUMBER,
        p_fecha_cobro IN DATE
    );
    PROCEDURE SP_ANULAR_CHEQUE(p_id_cheque IN NUMBER);
END PKG_CP_CHEQUE;
/

CREATE OR REPLACE PACKAGE BODY PKG_CP_CHEQUE AS

    PROCEDURE SP_LISTAR_CHEQUES(p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR
            SELECT ID_CHEQUE, ID_CONTRASENA_PAGO, BANCO, NUMERO_CHEQUE, FECHA_EMISION, FECHA_COBRO, ESTADO
            FROM CP_CHEQUE
            ORDER BY ID_CHEQUE DESC;
    END SP_LISTAR_CHEQUES;

    PROCEDURE SP_OBTENER_CHEQUE(p_id_cheque IN NUMBER, p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR
            SELECT ID_CHEQUE, ID_CONTRASENA_PAGO, BANCO, NUMERO_CHEQUE, FECHA_EMISION, FECHA_COBRO, ESTADO
            FROM CP_CHEQUE
            WHERE ID_CHEQUE = p_id_cheque;
    END SP_OBTENER_CHEQUE;

    PROCEDURE SP_INSERTAR_CHEQUE(
        p_id_contrasena_pago IN NUMBER,
        p_banco IN VARCHAR2,
        p_numero_cheque IN VARCHAR2,
        p_fecha_emision IN DATE,
        p_id_cheque_out OUT NUMBER
    ) IS
    BEGIN
        IF p_fecha_emision > TRUNC(SYSDATE) THEN
            RAISE_APPLICATION_ERROR(-20001, 'La fecha de emision no puede ser futura.');
        END IF;
        -- Valida que la contrasena sea CHEQUE y PENDIENTE, la pasa a EMITIDA
        -- y descuenta su monto del saldo de la factura.
        PKG_CP_CONTRASENA_PAGO.SP_EMITIR_PAGO(p_id_contrasena_pago);

        INSERT INTO CP_CHEQUE (ID_CONTRASENA_PAGO, BANCO, NUMERO_CHEQUE, FECHA_EMISION, ESTADO)
        VALUES (p_id_contrasena_pago, p_banco, p_numero_cheque, p_fecha_emision, 'EMITIDO')
        RETURNING ID_CHEQUE INTO p_id_cheque_out;
    END SP_INSERTAR_CHEQUE;

    PROCEDURE SP_ACTUALIZAR_CHEQUE(
        p_id_cheque IN NUMBER,
        p_banco IN VARCHAR2,
        p_numero_cheque IN VARCHAR2,
        p_fecha_emision IN DATE
    ) IS
        L_ESTADO VARCHAR2(20);
    BEGIN
        SELECT ESTADO INTO L_ESTADO FROM CP_CHEQUE WHERE ID_CHEQUE = p_id_cheque;
        IF L_ESTADO != 'EMITIDO' THEN
            RAISE_APPLICATION_ERROR(-20003, 'Solo se puede editar un cheque en estado EMITIDO.');
        END IF;
        UPDATE CP_CHEQUE
        SET BANCO = NVL(p_banco, BANCO),
            NUMERO_CHEQUE = NVL(p_numero_cheque, NUMERO_CHEQUE),
            FECHA_EMISION = NVL(p_fecha_emision, FECHA_EMISION)
        WHERE ID_CHEQUE = p_id_cheque;
    END SP_ACTUALIZAR_CHEQUE;

    PROCEDURE SP_COBRAR_CHEQUE(
        p_id_cheque IN NUMBER,
        p_fecha_cobro IN DATE
    ) IS
        L_ESTADO VARCHAR2(20);
        L_FECHA_EMISION DATE;
        L_ID_CONTRASENA NUMBER;
    BEGIN
        SELECT ESTADO, FECHA_EMISION, ID_CONTRASENA_PAGO INTO L_ESTADO, L_FECHA_EMISION, L_ID_CONTRASENA
        FROM CP_CHEQUE WHERE ID_CHEQUE = p_id_cheque;

        IF L_ESTADO != 'EMITIDO' THEN
            RAISE_APPLICATION_ERROR(-20002, 'Solo se puede cobrar un cheque en estado EMITIDO.');
        END IF;
        IF p_fecha_cobro < L_FECHA_EMISION THEN
            RAISE_APPLICATION_ERROR(-20004, 'La fecha de cobro no puede ser anterior a la fecha de emision.');
        END IF;

        UPDATE CP_CHEQUE
        SET ESTADO = 'COBRADO', FECHA_COBRO = p_fecha_cobro
        WHERE ID_CHEQUE = p_id_cheque;

        -- La contrasena pasa a PAGADA.
        PKG_CP_CONTRASENA_PAGO.SP_CONFIRMAR_PAGO(L_ID_CONTRASENA);
    END SP_COBRAR_CHEQUE;

    PROCEDURE SP_ANULAR_CHEQUE(p_id_cheque IN NUMBER) IS
        L_ESTADO VARCHAR2(20);
        L_ID_CONTRASENA NUMBER;
        L_OTROS_ACTIVOS NUMBER;
    BEGIN
        SELECT ESTADO, ID_CONTRASENA_PAGO INTO L_ESTADO, L_ID_CONTRASENA
        FROM CP_CHEQUE WHERE ID_CHEQUE = p_id_cheque;
        IF L_ESTADO != 'EMITIDO' THEN
            RAISE_APPLICATION_ERROR(-20002, 'Solo se puede anular un cheque en estado EMITIDO.');
        END IF;
        UPDATE CP_CHEQUE SET ESTADO = 'ANULADO' WHERE ID_CHEQUE = p_id_cheque;

        -- Si no le queda otro cheque activo, la contrasena vuelve a PENDIENTE
        -- y se repone el saldo de la factura.
        SELECT COUNT(*) INTO L_OTROS_ACTIVOS FROM CP_CHEQUE
        WHERE ID_CONTRASENA_PAGO = L_ID_CONTRASENA AND ESTADO IN ('EMITIDO', 'COBRADO');
        IF L_OTROS_ACTIVOS = 0 THEN
            PKG_CP_CONTRASENA_PAGO.SP_REVERTIR_EMISION(L_ID_CONTRASENA);
        END IF;
    END SP_ANULAR_CHEQUE;

END PKG_CP_CHEQUE;
/

-- ---- PKG_FACTURA_PROVEEDOR_DETALLE (backend/src/handlers/facturaProveedorDetalle.handler.ts) ----
-- Cada cambio en las lineas recalcula el total y el saldo de su documento
-- (PKG_CP_FACTURA_PROVEEDOR.SP_RECALCULAR). No se puede modificar el detalle de
-- un documento ANULADO o de una factura con contrasenas de pago activas, ni
-- dejar un documento sin lineas. Codigos de error de negocio: ORA-2013x.
CREATE OR REPLACE PACKAGE PKG_FACTURA_PROVEEDOR_DETALLE AS
    TYPE T_CURSOR IS REF CURSOR;

    PROCEDURE SP_INSERTAR_DETALLE (
        P_ID_FACTURA_PROVEEDOR IN CP_FACTURA_PROVEEDOR_DETALLE.ID_FACTURA_PROVEEDOR%TYPE,
        P_ID_ARTICULO          IN CP_FACTURA_PROVEEDOR_DETALLE.ID_ARTICULO%TYPE,
        P_DESCRIPCION          IN CP_FACTURA_PROVEEDOR_DETALLE.DESCRIPCION%TYPE,
        P_CANTIDAD             IN CP_FACTURA_PROVEEDOR_DETALLE.CANTIDAD%TYPE,
        P_PRECIO_UNITARIO      IN CP_FACTURA_PROVEEDOR_DETALLE.PRECIO_UNITARIO%TYPE,
        P_ID_UNIDAD_MEDIDA     IN CP_FACTURA_PROVEEDOR_DETALLE.ID_UNIDAD_MEDIDA%TYPE,
        P_ID_DETALLE_OUT       OUT CP_FACTURA_PROVEEDOR_DETALLE.ID_FACTURA_PROV_DETALLE%TYPE
    );

    PROCEDURE SP_LISTAR_DETALLE (
        P_ID_FACTURA_PROVEEDOR IN CP_FACTURA_PROVEEDOR_DETALLE.ID_FACTURA_PROVEEDOR%TYPE DEFAULT NULL,
        P_CURSOR OUT T_CURSOR
    );

    PROCEDURE SP_OBTENER_DETALLE (
        P_ID_FACTURA_PROV_DETALLE IN CP_FACTURA_PROVEEDOR_DETALLE.ID_FACTURA_PROV_DETALLE%TYPE,
        P_CURSOR OUT T_CURSOR
    );

    PROCEDURE SP_ACTUALIZAR_DETALLE (
        P_ID_FACTURA_PROV_DETALLE IN CP_FACTURA_PROVEEDOR_DETALLE.ID_FACTURA_PROV_DETALLE%TYPE,
        P_ID_ARTICULO             IN CP_FACTURA_PROVEEDOR_DETALLE.ID_ARTICULO%TYPE,
        P_DESCRIPCION             IN CP_FACTURA_PROVEEDOR_DETALLE.DESCRIPCION%TYPE,
        P_CANTIDAD                IN CP_FACTURA_PROVEEDOR_DETALLE.CANTIDAD%TYPE,
        P_PRECIO_UNITARIO         IN CP_FACTURA_PROVEEDOR_DETALLE.PRECIO_UNITARIO%TYPE,
        P_ID_UNIDAD_MEDIDA        IN CP_FACTURA_PROVEEDOR_DETALLE.ID_UNIDAD_MEDIDA%TYPE
    );

    PROCEDURE SP_ELIMINAR_DETALLE (
        P_ID_FACTURA_PROV_DETALLE IN CP_FACTURA_PROVEEDOR_DETALLE.ID_FACTURA_PROV_DETALLE%TYPE
    );
END PKG_FACTURA_PROVEEDOR_DETALLE;
/

CREATE OR REPLACE PACKAGE BODY PKG_FACTURA_PROVEEDOR_DETALLE AS

    PROCEDURE VALIDAR_LINEA(
        P_DESCRIPCION      IN VARCHAR2,
        P_CANTIDAD         IN NUMBER,
        P_PRECIO_UNITARIO  IN NUMBER,
        P_ID_UNIDAD_MEDIDA IN NUMBER
    ) IS
    BEGIN
        IF TRIM(P_DESCRIPCION) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20131, 'La descripcion de la linea es obligatoria.');
        END IF;
        IF P_CANTIDAD IS NULL OR P_CANTIDAD <= 0 THEN
            RAISE_APPLICATION_ERROR(-20131, 'La cantidad debe ser mayor a cero.');
        END IF;
        IF P_PRECIO_UNITARIO IS NULL OR P_PRECIO_UNITARIO <= 0 THEN
            RAISE_APPLICATION_ERROR(-20131, 'El precio unitario debe ser mayor a cero.');
        END IF;
        IF P_ID_UNIDAD_MEDIDA IS NULL THEN
            RAISE_APPLICATION_ERROR(-20131, 'La unidad de medida es obligatoria.');
        END IF;
    END VALIDAR_LINEA;

    -- Devuelve la factura duena de la linea, o error si la linea no existe.
    FUNCTION FACTURA_DE_LINEA(P_ID_DETALLE IN NUMBER) RETURN NUMBER IS
        L_ID NUMBER;
    BEGIN
        SELECT ID_FACTURA_PROVEEDOR INTO L_ID FROM CP_FACTURA_PROVEEDOR_DETALLE
        WHERE ID_FACTURA_PROV_DETALLE = P_ID_DETALLE;
        RETURN L_ID;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20132, 'La linea de detalle ' || P_ID_DETALLE || ' no existe.');
    END FACTURA_DE_LINEA;

    PROCEDURE SP_INSERTAR_DETALLE (
        P_ID_FACTURA_PROVEEDOR IN CP_FACTURA_PROVEEDOR_DETALLE.ID_FACTURA_PROVEEDOR%TYPE,
        P_ID_ARTICULO          IN CP_FACTURA_PROVEEDOR_DETALLE.ID_ARTICULO%TYPE,
        P_DESCRIPCION          IN CP_FACTURA_PROVEEDOR_DETALLE.DESCRIPCION%TYPE,
        P_CANTIDAD             IN CP_FACTURA_PROVEEDOR_DETALLE.CANTIDAD%TYPE,
        P_PRECIO_UNITARIO      IN CP_FACTURA_PROVEEDOR_DETALLE.PRECIO_UNITARIO%TYPE,
        P_ID_UNIDAD_MEDIDA     IN CP_FACTURA_PROVEEDOR_DETALLE.ID_UNIDAD_MEDIDA%TYPE,
        P_ID_DETALLE_OUT       OUT CP_FACTURA_PROVEEDOR_DETALLE.ID_FACTURA_PROV_DETALLE%TYPE
    ) IS
    BEGIN
        PKG_CP_FACTURA_PROVEEDOR.SP_VALIDAR_DETALLE_EDITABLE(P_ID_FACTURA_PROVEEDOR);
