CREATE OR REPLACE PACKAGE BODY PKG_CP_RETENCION AS

    PROCEDURE VALIDAR(p_id_factura IN NUMBER, p_monto IN NUMBER) IS
        L_TIPO VARCHAR2(20);
        L_ESTADO VARCHAR2(20);
    BEGIN
        BEGIN
            SELECT TIPO_DOCUMENTO, ESTADO INTO L_TIPO, L_ESTADO
            FROM CP_FACTURA_PROVEEDOR WHERE ID_FACTURA_PROVEEDOR = p_id_factura;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20140, 'La factura ' || p_id_factura || ' no existe.');
        END;
        IF L_TIPO NOT IN ('FACTURA', 'FACTURA_ESPECIAL') THEN
            RAISE_APPLICATION_ERROR(-20140, 'Las retenciones solo aplican a FACTURA o FACTURA ESPECIAL.');
        END IF;
        IF L_ESTADO = 'ANULADA' THEN
            RAISE_APPLICATION_ERROR(-20140, 'La factura ' || p_id_factura || ' esta ANULADA.');
        END IF;
        IF p_monto IS NULL OR p_monto <= 0 THEN
            RAISE_APPLICATION_ERROR(-20141, 'El monto de la retencion debe ser mayor a cero.');
        END IF;
    END VALIDAR;

    PROCEDURE SP_GET_ALL (p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR
            SELECT ID_RETENCION, ID_FACTURA_PROVEEDOR, TIPO_RETENCION, BASE_IMPONIBLE,
                   PORCENTAJE, MONTO, NUMERO_CONSTANCIA
            FROM CP_RETENCION
            ORDER BY ID_RETENCION DESC;
    END SP_GET_ALL;

    PROCEDURE SP_GET_BY_ID (p_id_retencion IN NUMBER, p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR
            SELECT ID_RETENCION, ID_FACTURA_PROVEEDOR, TIPO_RETENCION, BASE_IMPONIBLE,
                   PORCENTAJE, MONTO, NUMERO_CONSTANCIA
            FROM CP_RETENCION
            WHERE ID_RETENCION = p_id_retencion;
    END SP_GET_BY_ID;

    PROCEDURE SP_INSERT (
        p_id_factura_proveedor IN NUMBER,
        p_tipo_retencion IN VARCHAR2,
        p_base_imponible IN NUMBER,
        p_porcentaje IN NUMBER,
        p_monto IN NUMBER,
        p_numero_constancia IN VARCHAR2,
        p_id_out OUT NUMBER
    ) IS
    BEGIN
        VALIDAR(p_id_factura_proveedor, p_monto);
        INSERT INTO CP_RETENCION (
            ID_FACTURA_PROVEEDOR, TIPO_RETENCION, BASE_IMPONIBLE, PORCENTAJE, MONTO, NUMERO_CONSTANCIA
        ) VALUES (
            p_id_factura_proveedor, p_tipo_retencion, p_base_imponible, p_porcentaje, p_monto, p_numero_constancia
        ) RETURNING ID_RETENCION INTO p_id_out;

        PKG_CP_FACTURA_PROVEEDOR.SP_RECALCULAR(p_id_factura_proveedor);
    END SP_INSERT;

    PROCEDURE SP_UPDATE (
        p_id_retencion IN NUMBER,
        p_id_factura_proveedor IN NUMBER,
        p_tipo_retencion IN VARCHAR2,
        p_base_imponible IN NUMBER,
        p_porcentaje IN NUMBER,
        p_monto IN NUMBER,
        p_numero_constancia IN VARCHAR2
    ) IS
        L_FACTURA_ANTERIOR NUMBER;
    BEGIN
        BEGIN
            SELECT ID_FACTURA_PROVEEDOR INTO L_FACTURA_ANTERIOR FROM CP_RETENCION WHERE ID_RETENCION = p_id_retencion;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20142, 'La retencion ' || p_id_retencion || ' no existe.');
        END;
        VALIDAR(p_id_factura_proveedor, p_monto);

        UPDATE CP_RETENCION
        SET ID_FACTURA_PROVEEDOR = p_id_factura_proveedor,
            TIPO_RETENCION = p_tipo_retencion,
            BASE_IMPONIBLE = p_base_imponible,
            PORCENTAJE = p_porcentaje,
            MONTO = p_monto,
            NUMERO_CONSTANCIA = p_numero_constancia
        WHERE ID_RETENCION = p_id_retencion;

        PKG_CP_FACTURA_PROVEEDOR.SP_RECALCULAR(p_id_factura_proveedor);
        IF L_FACTURA_ANTERIOR != p_id_factura_proveedor THEN
            PKG_CP_FACTURA_PROVEEDOR.SP_RECALCULAR(L_FACTURA_ANTERIOR);
        END IF;
    END SP_UPDATE;

    PROCEDURE SP_DELETE (p_id_retencion IN NUMBER) IS
        L_FACTURA NUMBER;
    BEGIN
        BEGIN
            SELECT ID_FACTURA_PROVEEDOR INTO L_FACTURA FROM CP_RETENCION WHERE ID_RETENCION = p_id_retencion;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20142, 'La retencion ' || p_id_retencion || ' no existe.');
        END;
        DELETE FROM CP_RETENCION WHERE ID_RETENCION = p_id_retencion;
        PKG_CP_FACTURA_PROVEEDOR.SP_RECALCULAR(L_FACTURA);
    END SP_DELETE;
END PKG_CP_RETENCION;
