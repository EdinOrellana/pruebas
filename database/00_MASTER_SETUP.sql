CREATE OR REPLACE PACKAGE BODY CP_PKG_CAJA_CHICA_MOVIMIENTO AS

    FUNCTION TIPO_VALIDO (P_TIPO IN VARCHAR2) RETURN BOOLEAN IS
        L_TIPO VARCHAR2(20);
    BEGIN
        L_TIPO := UPPER(TRIM(P_TIPO));
        RETURN L_TIPO IN ('REPOSICION', 'GASTO', 'ANULADO');
    END TIPO_VALIDO;

    FUNCTION ES_EGRESO (P_TIPO IN VARCHAR2) RETURN BOOLEAN IS
        L_TIPO VARCHAR2(20);
    BEGIN
        L_TIPO := UPPER(TRIM(P_TIPO));
        RETURN L_TIPO = 'GASTO';
    END ES_EGRESO;

    FUNCTION OBTENER_SALDO (P_ID_CAJA_CHICA IN CP_CAJA_CHICA_MOVIMIENTO.ID_CAJA_CHICA%TYPE) RETURN NUMBER IS
        L_SALDO NUMBER(14, 2);
    BEGIN
        SELECT
            C.FONDO_ASIGNADO
            + NVL(SUM(CASE WHEN M.TIPO_MOVIMIENTO = 'REPOSICION' THEN M.MONTO ELSE 0 END), 0)
            - NVL(SUM(CASE WHEN M.TIPO_MOVIMIENTO = 'GASTO'      THEN M.MONTO ELSE 0 END), 0)
        INTO L_SALDO
        FROM CP_CAJA_CHICA C
        LEFT JOIN CP_CAJA_CHICA_MOVIMIENTO M ON M.ID_CAJA_CHICA = C.ID_CAJA_CHICA
        WHERE C.ID_CAJA_CHICA = P_ID_CAJA_CHICA
        GROUP BY C.FONDO_ASIGNADO;
        RETURN L_SALDO;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20010, 'La caja chica indicada no existe.');
    END OBTENER_SALDO;

    PROCEDURE INSERTAR (
        P_ID_CAJA_CHICA        IN  CP_CAJA_CHICA_MOVIMIENTO.ID_CAJA_CHICA%TYPE,
        P_TIPO_MOVIMIENTO      IN  CP_CAJA_CHICA_MOVIMIENTO.TIPO_MOVIMIENTO%TYPE,
        P_CONCEPTO             IN  CP_CAJA_CHICA_MOVIMIENTO.CONCEPTO%TYPE,
        P_MONTO                IN  CP_CAJA_CHICA_MOVIMIENTO.MONTO%TYPE,
        P_NUMERO_COMPROBANTE   IN  CP_CAJA_CHICA_MOVIMIENTO.NUMERO_COMPROBANTE%TYPE DEFAULT NULL,
        P_ID_MOVIMIENTO        OUT CP_CAJA_CHICA_MOVIMIENTO.ID_MOVIMIENTO_CAJA%TYPE
    ) IS
        L_TIPO  VARCHAR2(20);
        L_SALDO NUMBER(14, 2);
    BEGIN
        L_TIPO := UPPER(TRIM(P_TIPO_MOVIMIENTO));
        IF NOT TIPO_VALIDO(L_TIPO) THEN
            RAISE_APPLICATION_ERROR(-20001, 'Tipo de movimiento no válido: ' || L_TIPO);
        END IF;
        IF P_CONCEPTO IS NULL OR TRIM(P_CONCEPTO) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20002, 'El concepto del movimiento es obligatorio.');
        END IF;
        IF P_MONTO IS NULL OR P_MONTO <= 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'El monto debe ser mayor que cero.');
        END IF;
        L_SALDO := OBTENER_SALDO(P_ID_CAJA_CHICA);
        IF ES_EGRESO(L_TIPO) AND P_MONTO > L_SALDO THEN
            RAISE_APPLICATION_ERROR(-20004, 'Saldo insuficiente. Saldo disponible: Q ' || TO_CHAR(L_SALDO, 'FM999999990.00'));
        END IF;
        INSERT INTO CP_CAJA_CHICA_MOVIMIENTO (ID_CAJA_CHICA, FECHA, TIPO_MOVIMIENTO, CONCEPTO, MONTO, NUMERO_COMPROBANTE)
        VALUES (P_ID_CAJA_CHICA, SYSDATE, L_TIPO, TRIM(P_CONCEPTO), P_MONTO, TRIM(P_NUMERO_COMPROBANTE))
        RETURNING ID_MOVIMIENTO_CAJA INTO P_ID_MOVIMIENTO;
    END INSERTAR;

    PROCEDURE ANULAR (
        P_ID_MOVIMIENTO_CAJA IN CP_CAJA_CHICA_MOVIMIENTO.ID_MOVIMIENTO_CAJA%TYPE,
        P_MOTIVO             IN VARCHAR2
    ) IS
        L_TIPO_ACTUAL    VARCHAR2(20);
        L_CONCEPTO_ACTUAL VARCHAR2(300);
        L_MOTIVO_TRIM    VARCHAR2(200);
        L_CONCEPTO_NUEVO VARCHAR2(300);
    BEGIN
        IF P_ID_MOVIMIENTO_CAJA IS NULL THEN
            RAISE_APPLICATION_ERROR(-20005, 'El ID de movimiento es obligatorio.');
        END IF;
        IF P_MOTIVO IS NULL OR TRIM(P_MOTIVO) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20006, 'El motivo de anulación es obligatorio.');
        END IF;
        BEGIN
            SELECT TIPO_MOVIMIENTO, CONCEPTO
            INTO   L_TIPO_ACTUAL, L_CONCEPTO_ACTUAL
            FROM   CP_CAJA_CHICA_MOVIMIENTO
            WHERE  ID_MOVIMIENTO_CAJA = P_ID_MOVIMIENTO_CAJA;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20007, 'El movimiento indicado no existe.');
        END;
        IF UPPER(TRIM(L_TIPO_ACTUAL)) = 'ANULADO' THEN
            RAISE_APPLICATION_ERROR(-20008, 'El movimiento ya se encuentra anulado.');
        END IF;
        L_MOTIVO_TRIM    := SUBSTR(TRIM(P_MOTIVO), 1, 180);
        L_CONCEPTO_NUEVO := SUBSTR(TRIM(L_CONCEPTO_ACTUAL) || ' [ANULADO: ' || L_MOTIVO_TRIM || ']', 1, 300);
        UPDATE CP_CAJA_CHICA_MOVIMIENTO
        SET    TIPO_MOVIMIENTO = 'ANULADO', CONCEPTO = L_CONCEPTO_NUEVO
        WHERE  ID_MOVIMIENTO_CAJA = P_ID_MOVIMIENTO_CAJA;
    END ANULAR;

    PROCEDURE LISTAR (
        P_ID_CAJA_CHICA   IN  CP_CAJA_CHICA_MOVIMIENTO.ID_CAJA_CHICA%TYPE DEFAULT NULL,
        P_LIMITE          IN  NUMBER DEFAULT NULL,
        P_OFFSET          IN  NUMBER DEFAULT NULL,
        P_TOTAL_REGISTROS OUT NUMBER,
        P_CURSOR          OUT SYS_REFCURSOR
    ) IS
    BEGIN
        SELECT COUNT(*)
        INTO   P_TOTAL_REGISTROS
        FROM   CP_CAJA_CHICA_MOVIMIENTO M
        WHERE  (P_ID_CAJA_CHICA IS NULL OR M.ID_CAJA_CHICA = P_ID_CAJA_CHICA);

        OPEN P_CURSOR FOR
            SELECT
                M.ID_MOVIMIENTO_CAJA, M.ID_CAJA_CHICA, M.FECHA, M.TIPO_MOVIMIENTO,
                M.CONCEPTO, M.MONTO, M.NUMERO_COMPROBANTE,
                CP_PKG_CAJA_CHICA_MOVIMIENTO.OBTENER_SALDO(M.ID_CAJA_CHICA) AS SALDO_DISPONIBLE
            FROM CP_CAJA_CHICA_MOVIMIENTO M
            WHERE (P_ID_CAJA_CHICA IS NULL OR M.ID_CAJA_CHICA = P_ID_CAJA_CHICA)
            ORDER BY M.FECHA DESC, M.ID_MOVIMIENTO_CAJA DESC
            OFFSET NVL(P_OFFSET, 0) ROWS
            FETCH NEXT NVL(P_LIMITE, 1000000) ROWS ONLY;
    END LISTAR;

    PROCEDURE LISTAR_TIPOS (P_CURSOR OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT 'REPOSICION' AS CODIGO FROM DUAL
            UNION ALL
            SELECT 'GASTO' AS CODIGO FROM DUAL;
    END LISTAR_TIPOS;

END CP_PKG_CAJA_CHICA_MOVIMIENTO;
