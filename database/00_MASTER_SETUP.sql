-- Vista de facturas con proveedor, notas aplicadas y pagos emitidos
-- (la usan SP_LISTAR_FACTURAS / SP_OBTENER_FACTURA). Requiere la tabla
-- PROVEEDOR (DEPENDENCIAS_EXTERNAS o SCRIPT_GENERAL.sql).
CREATE OR REPLACE VIEW VW_CP_FACTURA_PROVEEDOR AS
SELECT F.ID_FACTURA_PROVEEDOR,
       F.ID_PROVEEDOR,
       P.NIT AS NIT_PROVEEDOR,
       P.RAZON_SOCIAL AS NOMBRE_PROVEEDOR,
       F.TIPO_DOCUMENTO,
       F.NUMERO_DTE,
       F.SERIE_DTE,
       F.FECHA_EMISION,
       F.FECHA_DOCUMENTO,
       F.FECHA_VENCIMIENTO,
       F.MONTO_TOTAL,
       F.MONTO_RETENCION_IVA,
       F.MONTO_RETENCION_ISR,
       F.SALDO_PENDIENTE,
       F.ESTADO,
       F.ID_FACTURA_REFERENCIA,
       F.NOTAS,
       NVL(N.MONTO_NC, 0) AS MONTO_NOTAS_CREDITO,
       NVL(N.MONTO_ND, 0) AS MONTO_NOTAS_DEBITO,
       NVL(N.NOTAS_ACTIVAS, 0) AS NOTAS_ACTIVAS,
       NVL(C.MONTO_PAGADO, 0) AS MONTO_PAGADO,
       NVL(C.CONTRASENAS_ACTIVAS, 0) AS CONTRASENAS_ACTIVAS
FROM CP_FACTURA_PROVEEDOR F
LEFT JOIN PROVEEDOR P ON P.ID_PROVEEDOR = F.ID_PROVEEDOR
LEFT JOIN (
    SELECT ID_FACTURA_REFERENCIA,
           SUM(CASE WHEN TIPO_DOCUMENTO = 'NOTA_CREDITO' THEN MONTO_TOTAL END) AS MONTO_NC,
           SUM(CASE WHEN TIPO_DOCUMENTO = 'NOTA_DEBITO' THEN MONTO_TOTAL END) AS MONTO_ND,
           COUNT(*) AS NOTAS_ACTIVAS
    FROM CP_FACTURA_PROVEEDOR
    WHERE ID_FACTURA_REFERENCIA IS NOT NULL AND ESTADO != 'ANULADA'
    GROUP BY ID_FACTURA_REFERENCIA
) N ON N.ID_FACTURA_REFERENCIA = F.ID_FACTURA_PROVEEDOR
LEFT JOIN (
    SELECT ID_FACTURA_PROVEEDOR,
           SUM(CASE WHEN ESTADO IN ('EMITIDA', 'PAGADA') THEN MONTO END) AS MONTO_PAGADO,
           SUM(CASE WHEN ESTADO != 'ANULADA' THEN 1 ELSE 0 END) AS CONTRASENAS_ACTIVAS
    FROM CP_CONTRASENA_PAGO
    GROUP BY ID_FACTURA_PROVEEDOR
) C ON C.ID_FACTURA_PROVEEDOR = F.ID_FACTURA_PROVEEDOR;


