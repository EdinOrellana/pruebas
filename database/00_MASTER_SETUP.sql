             ROUND(P_CANTIDAD * P_PRECIO_UNITARIO, 2))
        RETURNING ID_FACTURA_PROV_DETALLE INTO P_ID_DETALLE_OUT;

        PKG_CP_FACTURA_PROVEEDOR.SP_RECALCULAR(P_ID_FACTURA_PROVEEDOR);
