-- ---- PKG_CP_CONTRASENA_PAGO (backend/src/handlers/contrasenaPago.handler.ts) ----
-- Ciclo de vida de una contraseña de pago y su efecto en la factura:
--   PENDIENTE --(registrar cheque / registrar pago)--> EMITIDA / PAGADA
--   EMITIDA   --(cobrar cheque)--> PAGADA
--   EMITIDA   --(anular cheque)--> PENDIENTE (se repone el saldo)
--   PENDIENTE --(anular)--> ANULADA
-- El SALDO_PENDIENTE de la factura baja al EMITIR el pago (al salir de
-- PENDIENTE) y sube de nuevo si el cheque se anula: tras cada cambio de estado
-- se llama PKG_CP_FACTURA_PROVEEDOR.SP_RECALCULAR (por eso va despues de ese
-- paquete). Va antes que PKG_CP_CHEQUE porque ese paquete llama a
-- SP_EMITIR_PAGO / SP_CONFIRMAR_PAGO / SP_REVERTIR_EMISION.
-- Codigos de error de negocio (ORA-201xx); el backend los devuelve como 400.
CREATE OR REPLACE PACKAGE PKG_CP_CONTRASENA_PAGO AS
    PROCEDURE SP_LISTAR_CONTRASENAS(p_cursor OUT SYS_REFCURSOR);
    PROCEDURE SP_OBTENER_CONTRASENA(p_id_contrasena IN NUMBER, p_cursor OUT SYS_REFCURSOR);
    PROCEDURE SP_INSERTAR_CONTRASENA(
        p_id_factura_proveedor IN NUMBER,
        p_fecha IN DATE,
        p_forma_pago IN VARCHAR2,
        p_monto IN NUMBER,
        p_id_empleado_autoriza IN NUMBER,
        p_id_contrasena_out OUT NUMBER
    );
    PROCEDURE SP_ACTUALIZAR_CONTRASENA(
        p_id_contrasena IN NUMBER,
        p_forma_pago IN VARCHAR2,
        p_monto IN NUMBER,
        p_id_empleado_autoriza IN NUMBER
    );
    -- Requiere un motivo escrito; se guarda en NOTAS.
    PROCEDURE SP_ANULAR_CONTRASENA(p_id_contrasena IN NUMBER, p_motivo IN VARCHAR2);
    -- Pago directo (TRANSFERENCIA / EFECTIVO): PENDIENTE -> PAGADA y baja el saldo.
    PROCEDURE SP_REGISTRAR_PAGO(p_id_contrasena IN NUMBER);
    -- Usados por PKG_CP_CHEQUE:
    PROCEDURE SP_EMITIR_PAGO(p_id_contrasena IN NUMBER);
    PROCEDURE SP_CONFIRMAR_PAGO(p_id_contrasena IN NUMBER);
    PROCEDURE SP_REVERTIR_EMISION(p_id_contrasena IN NUMBER);
END PKG_CP_CONTRASENA_PAGO;
/

CREATE OR REPLACE PACKAGE BODY PKG_CP_CONTRASENA_PAGO AS

    -- Lee y BLOQUEA la contraseña (evita que dos usuarios la muevan a la vez).
    PROCEDURE LEER_CONTRASENA(
        p_id_contrasena IN NUMBER,
        p_row OUT CP_CONTRASENA_PAGO%ROWTYPE
    ) IS
    BEGIN
        SELECT * INTO p_row FROM CP_CONTRASENA_PAGO
        WHERE ID_CONTRASENA = p_id_contrasena
        FOR UPDATE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20106, 'La contrasena de pago ' || p_id_contrasena || ' no existe.');
    END LEER_CONTRASENA;

    -- Lee y BLOQUEA la factura, validando que exista.
    PROCEDURE LEER_FACTURA(
        p_id_factura IN NUMBER,
        p_row OUT CP_FACTURA_PROVEEDOR%ROWTYPE
    ) IS
    BEGIN
        SELECT * INTO p_row FROM CP_FACTURA_PROVEEDOR
        WHERE ID_FACTURA_PROVEEDOR = p_id_factura
        FOR UPDATE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20101, 'La factura ' || p_id_factura || ' no existe.');
    END LEER_FACTURA;

    -- Valida monto > 0 y que no exceda lo disponible de la factura:
    -- disponible = SALDO_PENDIENTE - montos de otras contraseñas PENDIENTES
    -- (las EMITIDAS/PAGADAS ya estan descontadas del saldo).
    PROCEDURE VALIDAR_MONTO(
        p_factura IN CP_FACTURA_PROVEEDOR%ROWTYPE,
        p_monto IN NUMBER,
        p_excluir_contrasena IN NUMBER
    ) IS
        L_COMPROMETIDO NUMBER;
        L_DISPONIBLE NUMBER;
    BEGIN
        IF p_monto IS NULL OR p_monto <= 0 THEN
            RAISE_APPLICATION_ERROR(-20103, 'El monto debe ser mayor a cero.');
        END IF;

        SELECT NVL(SUM(MONTO), 0) INTO L_COMPROMETIDO
        FROM CP_CONTRASENA_PAGO
        WHERE ID_FACTURA_PROVEEDOR = p_factura.ID_FACTURA_PROVEEDOR
          AND ESTADO = 'PENDIENTE'
          AND ID_CONTRASENA != NVL(p_excluir_contrasena, -1);

        L_DISPONIBLE := p_factura.SALDO_PENDIENTE - L_COMPROMETIDO;
        IF p_monto > L_DISPONIBLE THEN
            RAISE_APPLICATION_ERROR(-20104,
                'El monto (Q' || TO_CHAR(p_monto, 'FM999,999,990.00') ||
                ') excede lo disponible de la factura (Q' || TO_CHAR(GREATEST(L_DISPONIBLE, 0), 'FM999,999,990.00') ||
                '). Saldo pendiente: Q' || TO_CHAR(p_factura.SALDO_PENDIENTE, 'FM999,999,990.00') ||
                ', comprometido en otras contrasenas pendientes: Q' || TO_CHAR(L_COMPROMETIDO, 'FM999,999,990.00') || '.');
        END IF;
    END VALIDAR_MONTO;

    PROCEDURE VALIDAR_EMPLEADO(p_id_empleado IN NUMBER) IS
        L_EXISTE NUMBER;
    BEGIN
        IF p_id_empleado IS NULL THEN
            RETURN;
        END IF;
        SELECT COUNT(*) INTO L_EXISTE FROM NOM_EMPLEADO
        WHERE ID_EMPLEADO = p_id_empleado AND ESTADO = 'A' AND ELIMINADO = 'N';
        IF L_EXISTE = 0 THEN
            RAISE_APPLICATION_ERROR(-20105, 'El empleado que autoriza (' || p_id_empleado || ') no existe o no esta activo.');
        END IF;
    END VALIDAR_EMPLEADO;

    -- Valida que la factura admita un pago de p_monto (antes de cambiar el estado).
    -- El saldo y el estado de la factura los calcula PKG_CP_FACTURA_PROVEEDOR.SP_RECALCULAR.
    PROCEDURE VALIDAR_PAGO(p_id_factura IN NUMBER, p_monto IN NUMBER) IS
        L_FACTURA CP_FACTURA_PROVEEDOR%ROWTYPE;
    BEGIN
        LEER_FACTURA(p_id_factura, L_FACTURA);
        IF L_FACTURA.ESTADO = 'ANULADA' THEN
            RAISE_APPLICATION_ERROR(-20102, 'La factura ' || p_id_factura || ' esta ANULADA; no admite pagos.');
        END IF;
        IF p_monto > L_FACTURA.SALDO_PENDIENTE THEN
            RAISE_APPLICATION_ERROR(-20104,
                'El pago (Q' || TO_CHAR(p_monto, 'FM999,999,990.00') ||
                ') excede el saldo pendiente de la factura (Q' || TO_CHAR(L_FACTURA.SALDO_PENDIENTE, 'FM999,999,990.00') || ').');
        END IF;
    END VALIDAR_PAGO;

    PROCEDURE SP_LISTAR_CONTRASENAS(p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR
            SELECT ID_CONTRASENA, ID_FACTURA_PROVEEDOR, FECHA, FORMA_PAGO, ESTADO, MONTO, ID_EMPLEADO_AUTORIZA, NOTAS
            FROM CP_CONTRASENA_PAGO
            ORDER BY ID_CONTRASENA DESC;
    END SP_LISTAR_CONTRASENAS;

    PROCEDURE SP_OBTENER_CONTRASENA(p_id_contrasena IN NUMBER, p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR
            SELECT ID_CONTRASENA, ID_FACTURA_PROVEEDOR, FECHA, FORMA_PAGO, ESTADO, MONTO, ID_EMPLEADO_AUTORIZA, NOTAS
            FROM CP_CONTRASENA_PAGO
            WHERE ID_CONTRASENA = p_id_contrasena;
    END SP_OBTENER_CONTRASENA;

    PROCEDURE SP_INSERTAR_CONTRASENA(
        p_id_factura_proveedor IN NUMBER,
        p_fecha IN DATE,
        p_forma_pago IN VARCHAR2,
        p_monto IN NUMBER,
        p_id_empleado_autoriza IN NUMBER,
        p_id_contrasena_out OUT NUMBER
    ) IS
        L_FACTURA CP_FACTURA_PROVEEDOR%ROWTYPE;
    BEGIN
        LEER_FACTURA(p_id_factura_proveedor, L_FACTURA);
        IF L_FACTURA.TIPO_DOCUMENTO NOT IN ('FACTURA', 'FACTURA_ESPECIAL') THEN
            RAISE_APPLICATION_ERROR(-20113,
                'Las notas de credito y debito no se pagan: se aplican a su factura. Genere la contrasena sobre la factura.');
        END IF;
        IF L_FACTURA.ESTADO NOT IN ('PENDIENTE', 'PAGADA_PARCIAL') THEN
            RAISE_APPLICATION_ERROR(-20102,
                'La factura ' || p_id_factura_proveedor || ' esta ' || L_FACTURA.ESTADO || '; solo se generan contrasenas para facturas PENDIENTES o PAGADAS PARCIALMENTE.');
        END IF;
        VALIDAR_MONTO(L_FACTURA, p_monto, NULL);
        VALIDAR_EMPLEADO(p_id_empleado_autoriza);

        INSERT INTO CP_CONTRASENA_PAGO (ID_FACTURA_PROVEEDOR, FECHA, FORMA_PAGO, ESTADO, MONTO, ID_EMPLEADO_AUTORIZA)
        VALUES (p_id_factura_proveedor, p_fecha, p_forma_pago, 'PENDIENTE', p_monto, p_id_empleado_autoriza)
        RETURNING ID_CONTRASENA INTO p_id_contrasena_out;
    END SP_INSERTAR_CONTRASENA;

    PROCEDURE SP_ACTUALIZAR_CONTRASENA(
        p_id_contrasena IN NUMBER,
        p_forma_pago IN VARCHAR2,
        p_monto IN NUMBER,
        p_id_empleado_autoriza IN NUMBER
    ) IS
        L_CONTRASENA CP_CONTRASENA_PAGO%ROWTYPE;
        L_FACTURA CP_FACTURA_PROVEEDOR%ROWTYPE;
    BEGIN
        LEER_CONTRASENA(p_id_contrasena, L_CONTRASENA);
        IF L_CONTRASENA.ESTADO != 'PENDIENTE' THEN
            RAISE_APPLICATION_ERROR(-20107,
                'Solo se puede editar una contrasena PENDIENTE (esta esta ' || L_CONTRASENA.ESTADO || ').');
        END IF;
        LEER_FACTURA(L_CONTRASENA.ID_FACTURA_PROVEEDOR, L_FACTURA);
        VALIDAR_MONTO(L_FACTURA, p_monto, p_id_contrasena);
        VALIDAR_EMPLEADO(p_id_empleado_autoriza);

        UPDATE CP_CONTRASENA_PAGO
        SET FORMA_PAGO = p_forma_pago, MONTO = p_monto, ID_EMPLEADO_AUTORIZA = p_id_empleado_autoriza
        WHERE ID_CONTRASENA = p_id_contrasena;
    END SP_ACTUALIZAR_CONTRASENA;

    PROCEDURE SP_ANULAR_CONTRASENA(p_id_contrasena IN NUMBER, p_motivo IN VARCHAR2) IS
        L_CONTRASENA CP_CONTRASENA_PAGO%ROWTYPE;
        L_CHEQUES_ACTIVOS NUMBER;
    BEGIN
        IF p_motivo IS NULL OR TRIM(p_motivo) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20114, 'El motivo de anulacion es obligatorio.');
        END IF;
        LEER_CONTRASENA(p_id_contrasena, L_CONTRASENA);
        IF L_CONTRASENA.ESTADO = 'EMITIDA' THEN
            RAISE_APPLICATION_ERROR(-20108,
                'La contrasena tiene un pago EMITIDO; anule primero el cheque para devolverla a PENDIENTE.');
        ELSIF L_CONTRASENA.ESTADO != 'PENDIENTE' THEN
            RAISE_APPLICATION_ERROR(-20108,
                'Solo se puede anular una contrasena PENDIENTE (esta esta ' || L_CONTRASENA.ESTADO || ').');
        END IF;

        SELECT COUNT(*) INTO L_CHEQUES_ACTIVOS FROM CP_CHEQUE
        WHERE ID_CONTRASENA_PAGO = p_id_contrasena AND ESTADO IN ('EMITIDO', 'COBRADO');
        IF L_CHEQUES_ACTIVOS > 0 THEN
            RAISE_APPLICATION_ERROR(-20108,
                'La contrasena tiene cheques EMITIDOS o COBRADOS; anule primero esos cheques.');
        END IF;

        -- PENDIENTE aun no desconto saldo de la factura: no hay nada que reponer.
        -- El motivo queda registrado en NOTAS.
        UPDATE CP_CONTRASENA_PAGO
        SET ESTADO = 'ANULADA',
            NOTAS = SUBSTR(TRIM(p_motivo), 1, 300)
        WHERE ID_CONTRASENA = p_id_contrasena;
    END SP_ANULAR_CONTRASENA;

    PROCEDURE SP_REGISTRAR_PAGO(p_id_contrasena IN NUMBER) IS
        L_CONTRASENA CP_CONTRASENA_PAGO%ROWTYPE;
    BEGIN
        LEER_CONTRASENA(p_id_contrasena, L_CONTRASENA);
        IF L_CONTRASENA.FORMA_PAGO = 'CHEQUE' THEN
            RAISE_APPLICATION_ERROR(-20109,
                'La forma de pago es CHEQUE: registre el cheque en la vista de Cheques y cobrelo alli.');
        END IF;
        IF L_CONTRASENA.ESTADO != 'PENDIENTE' THEN
            RAISE_APPLICATION_ERROR(-20110,
                'Solo se puede registrar el pago de una contrasena PENDIENTE (esta esta ' || L_CONTRASENA.ESTADO || ').');
        END IF;

        VALIDAR_PAGO(L_CONTRASENA.ID_FACTURA_PROVEEDOR, L_CONTRASENA.MONTO);
        UPDATE CP_CONTRASENA_PAGO SET ESTADO = 'PAGADA' WHERE ID_CONTRASENA = p_id_contrasena;
        PKG_CP_FACTURA_PROVEEDOR.SP_RECALCULAR(L_CONTRASENA.ID_FACTURA_PROVEEDOR);
    END SP_REGISTRAR_PAGO;

    PROCEDURE SP_EMITIR_PAGO(p_id_contrasena IN NUMBER) IS
        L_CONTRASENA CP_CONTRASENA_PAGO%ROWTYPE;
    BEGIN
        LEER_CONTRASENA(p_id_contrasena, L_CONTRASENA);
        IF L_CONTRASENA.FORMA_PAGO != 'CHEQUE' THEN
            RAISE_APPLICATION_ERROR(-20111,
                'La contrasena ' || p_id_contrasena || ' es de forma de pago ' || L_CONTRASENA.FORMA_PAGO || '; no admite cheque.');
        END IF;
        IF L_CONTRASENA.ESTADO != 'PENDIENTE' THEN
            RAISE_APPLICATION_ERROR(-20112,
                'Solo se puede emitir cheque para una contrasena PENDIENTE (esta esta ' || L_CONTRASENA.ESTADO || ').');
        END IF;

        VALIDAR_PAGO(L_CONTRASENA.ID_FACTURA_PROVEEDOR, L_CONTRASENA.MONTO);
        UPDATE CP_CONTRASENA_PAGO SET ESTADO = 'EMITIDA' WHERE ID_CONTRASENA = p_id_contrasena;
        PKG_CP_FACTURA_PROVEEDOR.SP_RECALCULAR(L_CONTRASENA.ID_FACTURA_PROVEEDOR);
    END SP_EMITIR_PAGO;

    PROCEDURE SP_CONFIRMAR_PAGO(p_id_contrasena IN NUMBER) IS
        L_CONTRASENA CP_CONTRASENA_PAGO%ROWTYPE;
    BEGIN
        LEER_CONTRASENA(p_id_contrasena, L_CONTRASENA);
        IF L_CONTRASENA.ESTADO = 'EMITIDA' THEN
            UPDATE CP_CONTRASENA_PAGO SET ESTADO = 'PAGADA' WHERE ID_CONTRASENA = p_id_contrasena;
        ELSIF L_CONTRASENA.ESTADO = 'PENDIENTE' THEN
            -- Dato heredado (cheque emitido antes de estas reglas): el saldo aun no se desconto.
            VALIDAR_PAGO(L_CONTRASENA.ID_FACTURA_PROVEEDOR, L_CONTRASENA.MONTO);
            UPDATE CP_CONTRASENA_PAGO SET ESTADO = 'PAGADA' WHERE ID_CONTRASENA = p_id_contrasena;
            PKG_CP_FACTURA_PROVEEDOR.SP_RECALCULAR(L_CONTRASENA.ID_FACTURA_PROVEEDOR);
        ELSIF L_CONTRASENA.ESTADO = 'ANULADA' THEN
            RAISE_APPLICATION_ERROR(-20110, 'La contrasena ' || p_id_contrasena || ' esta ANULADA; no se puede confirmar su pago.');
        END IF;
        -- PAGADA: ya estaba confirmada, no hay cambios.
    END SP_CONFIRMAR_PAGO;

    PROCEDURE SP_REVERTIR_EMISION(p_id_contrasena IN NUMBER) IS
        L_CONTRASENA CP_CONTRASENA_PAGO%ROWTYPE;
    BEGIN
        LEER_CONTRASENA(p_id_contrasena, L_CONTRASENA);
        -- Solo una EMITIDA desconto saldo por el cheque; en otro estado no se toca.
        IF L_CONTRASENA.ESTADO = 'EMITIDA' THEN
            UPDATE CP_CONTRASENA_PAGO SET ESTADO = 'PENDIENTE' WHERE ID_CONTRASENA = p_id_contrasena;
            PKG_CP_FACTURA_PROVEEDOR.SP_RECALCULAR(L_CONTRASENA.ID_FACTURA_PROVEEDOR);
        END IF;
    END SP_REVERTIR_EMISION;

END PKG_CP_CONTRASENA_PAGO;
