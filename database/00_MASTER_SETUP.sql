CREATE OR REPLACE PACKAGE BODY PKG_CAJA_CHICA AS

    PROCEDURE SP_LISTAR_CAJAS_CHICAS(p_cursor OUT SYS_REFCURSOR) AS
    BEGIN
        OPEN p_cursor FOR
            SELECT
                c.ID_CAJA_CHICA, c.ID_SUCURSAL, s.NOMBRE AS SUCURSAL_NOMBRE, s.CODIGO AS SUCURSAL_CODIGO,
                c.ID_EMPLEADO_RESPONSABLE, (e.NOMBRES || ' ' || e.APELLIDOS) AS RESPONSABLE_NOMBRE,
                e.CODIGO_EMPLEADO AS RESPONSABLE_CODIGO, c.FONDO_ASIGNADO, c.ESTADO
            FROM CP_CAJA_CHICA c
            INNER JOIN NOM_SUCURSAL s ON c.ID_SUCURSAL = s.ID_SUCURSAL
            INNER JOIN NOM_EMPLEADO e ON c.ID_EMPLEADO_RESPONSABLE = e.ID_EMPLEADO
            WHERE c.ELIMINADO = 'N'
            ORDER BY c.ID_CAJA_CHICA DESC;
    END SP_LISTAR_CAJAS_CHICAS;

    PROCEDURE SP_OBTENER_CAJA_CHICA(p_id_caja_chica IN NUMBER, p_cursor OUT SYS_REFCURSOR) AS
    BEGIN
        OPEN p_cursor FOR
            SELECT
                c.ID_CAJA_CHICA, c.ID_SUCURSAL, s.NOMBRE AS SUCURSAL_NOMBRE, s.CODIGO AS SUCURSAL_CODIGO,
                c.ID_EMPLEADO_RESPONSABLE, (e.NOMBRES || ' ' || e.APELLIDOS) AS RESPONSABLE_NOMBRE,
                e.CODIGO_EMPLEADO AS RESPONSABLE_CODIGO, c.FONDO_ASIGNADO, c.ESTADO
            FROM CP_CAJA_CHICA c
            INNER JOIN NOM_SUCURSAL s ON c.ID_SUCURSAL = s.ID_SUCURSAL
            INNER JOIN NOM_EMPLEADO e ON c.ID_EMPLEADO_RESPONSABLE = e.ID_EMPLEADO
            WHERE c.ID_CAJA_CHICA = p_id_caja_chica AND c.ELIMINADO = 'N';
    END SP_OBTENER_CAJA_CHICA;

    PROCEDURE SP_INSERTAR_CAJA_CHICA(
        p_id_sucursal IN NUMBER,
        p_id_empleado_responsable IN NUMBER,
        p_fondo_asignado IN NUMBER,
        p_id_caja_chica_out OUT NUMBER
    ) AS
    BEGIN
        INSERT INTO CP_CAJA_CHICA (ID_SUCURSAL, ID_EMPLEADO_RESPONSABLE, FONDO_ASIGNADO, ESTADO, ELIMINADO)
        VALUES (p_id_sucursal, p_id_empleado_responsable, p_fondo_asignado, 'A', 'N')
        RETURNING ID_CAJA_CHICA INTO p_id_caja_chica_out;
    END SP_INSERTAR_CAJA_CHICA;

    PROCEDURE SP_ACTUALIZAR_CAJA_CHICA(
        p_id_caja_chica IN NUMBER,
        p_id_empleado_responsable IN NUMBER,
        p_fondo_asignado IN NUMBER,
        p_estado IN VARCHAR2
    ) AS
    BEGIN
        UPDATE CP_CAJA_CHICA
        SET ID_EMPLEADO_RESPONSABLE = p_id_empleado_responsable,
            FONDO_ASIGNADO = p_fondo_asignado,
            ESTADO = NVL(p_estado, ESTADO)
        WHERE ID_CAJA_CHICA = p_id_caja_chica AND ELIMINADO = 'N';
    END SP_ACTUALIZAR_CAJA_CHICA;

    PROCEDURE SP_INACTIVAR_CAJA_CHICA(
        p_id_caja_chica IN NUMBER,
        p_eliminado_por IN NUMBER DEFAULT NULL
    ) AS
    BEGIN
        UPDATE CP_CAJA_CHICA
        SET ESTADO = 'I', ELIMINADO = 'S', FECHA_ELIMINACION = SYSTIMESTAMP,
            ELIMINADO_POR = NVL(p_eliminado_por, ELIMINADO_POR)
        WHERE ID_CAJA_CHICA = p_id_caja_chica;
    END SP_INACTIVAR_CAJA_CHICA;

    PROCEDURE SP_LISTAR_SUCURSALES(p_cursor OUT SYS_REFCURSOR) AS
    BEGIN
        OPEN p_cursor FOR
            SELECT ID_SUCURSAL, CODIGO, NOMBRE FROM NOM_SUCURSAL
            WHERE ESTADO = 'A' AND ELIMINADO = 'N'
            ORDER BY NOMBRE ASC;
    END SP_LISTAR_SUCURSALES;

    PROCEDURE SP_LISTAR_EMPLEADOS(p_cursor OUT SYS_REFCURSOR) AS
    BEGIN
        OPEN p_cursor FOR
            SELECT ID_EMPLEADO, CODIGO_EMPLEADO, (NOMBRES || ' ' || APELLIDOS) AS NOMBRE_COMPLETO, ID_SUCURSAL
            FROM NOM_EMPLEADO
            WHERE ESTADO = 'A' AND ELIMINADO = 'N'
            ORDER BY NOMBRES ASC;
    END SP_LISTAR_EMPLEADOS;

END PKG_CAJA_CHICA;
