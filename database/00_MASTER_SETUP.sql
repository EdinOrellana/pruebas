-- ---- PKG_CP_FACTURA_PROVEEDOR (backend/src/handlers/facturaProveedor.handler.ts) ----
-- Reglas de la factura de proveedor:
--   * MONTO_TOTAL = suma de sus lineas de detalle (minimo una linea).
--   * MONTO_RETENCION_IVA / ISR = suma de CP_RETENCION (se registran en la vista Retenciones).
--   * Neto a pagar = total - retenciones - notas de credito + notas de debito aplicadas.
--   * SALDO_PENDIENTE = neto - pagos emitidos (contrasenas EMITIDA / PAGADA).
--   * NOTA_CREDITO / NOTA_DEBITO se aplican a una factura (ID_FACTURA_REFERENCIA),
--     no se pagan: quedan con saldo 0 y estado APLICADA.
-- SP_RECALCULAR es el UNICO lugar que calcula totales, saldo y estado; lo llaman
-- este paquete y los de contrasenas, detalle y retenciones despues de cada cambio.
-- Requiere la tabla PROVEEDOR (DEPENDENCIAS_EXTERNAS o SCRIPT_GENERAL.sql) y la vista
-- VW_CP_FACTURA_PROVEEDOR (Fase 3.5 de este archivo).
-- Codigos de error de negocio: ORA-2012x.
CREATE OR REPLACE PACKAGE PKG_CP_FACTURA_PROVEEDOR AS
    PROCEDURE SP_LISTAR_FACTURAS(p_cursor OUT SYS_REFCURSOR);
    PROCEDURE SP_OBTENER_FACTURA(p_id_factura IN NUMBER, p_cursor OUT SYS_REFCURSOR, p_cursor_detalle OUT SYS_REFCURSOR);
    PROCEDURE SP_LISTAR_PROVEEDORES(p_cursor OUT SYS_REFCURSOR);
    -- Crea el encabezado con total 0; las lineas se agregan despues con
    -- PKG_FACTURA_PROVEEDOR_DETALLE.SP_INSERTAR_DETALLE en la MISMA transaccion
    -- y se cierra con SP_VALIDAR_TIENE_DETALLE.
    PROCEDURE SP_INSERTAR_FACTURA(
        p_id_proveedor IN NUMBER,
        p_tipo_documento IN VARCHAR2,
        p_numero_dte IN VARCHAR2,
        p_serie_dte IN VARCHAR2,
        p_fecha_emision IN DATE,
        p_fecha_documento IN DATE,
        p_fecha_vencimiento IN DATE,
        p_id_factura_referencia IN NUMBER,
        p_id_factura_out OUT NUMBER
    );
    PROCEDURE SP_VALIDAR_TIENE_DETALLE(p_id_factura IN NUMBER);
    PROCEDURE SP_ACTUALIZAR_FACTURA(
        p_id_factura IN NUMBER,
        p_id_proveedor IN NUMBER,
        p_numero_dte IN VARCHAR2,
        p_serie_dte IN VARCHAR2,
        p_fecha_emision IN DATE,
        p_fecha_documento IN DATE,
        p_fecha_vencimiento IN DATE,
        p_id_factura_referencia IN NUMBER
    );
    -- Requiere un motivo escrito; se guarda en NOTAS.
    PROCEDURE SP_ANULAR_FACTURA(p_id_factura IN NUMBER, p_motivo IN VARCHAR2);
    -- Valida que se puedan modificar las lineas de detalle (usado por PKG_FACTURA_PROVEEDOR_DETALLE).
    PROCEDURE SP_VALIDAR_DETALLE_EDITABLE(p_id_factura IN NUMBER);
    -- Recalcula total, retenciones, saldo y estado (y los de su factura de referencia).
    PROCEDURE SP_RECALCULAR(p_id_factura IN NUMBER);
END PKG_CP_FACTURA_PROVEEDOR;
/

CREATE OR REPLACE PACKAGE BODY PKG_CP_FACTURA_PROVEEDOR AS

    FUNCTION Q(p_monto IN NUMBER) RETURN VARCHAR2 IS
    BEGIN
        RETURN 'Q' || TO_CHAR(NVL(p_monto, 0), 'FM999,999,990.00');
    END Q;

    FUNCTION ES_NOTA(p_tipo IN VARCHAR2) RETURN BOOLEAN IS
    BEGIN
        RETURN p_tipo IN ('NOTA_CREDITO', 'NOTA_DEBITO');
    END ES_NOTA;

    PROCEDURE LEER_FACTURA(p_id_factura IN NUMBER, p_row OUT CP_FACTURA_PROVEEDOR%ROWTYPE) IS
    BEGIN
        SELECT * INTO p_row FROM CP_FACTURA_PROVEEDOR
        WHERE ID_FACTURA_PROVEEDOR = p_id_factura
        FOR UPDATE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20125, 'La factura ' || p_id_factura || ' no existe.');
    END LEER_FACTURA;

    -- Contrasenas no anuladas (PENDIENTE / EMITIDA / PAGADA) de la factura.
    FUNCTION CONTRASENAS_ACTIVAS(p_id_factura IN NUMBER) RETURN NUMBER IS
        L_N NUMBER;
    BEGIN
        SELECT COUNT(*) INTO L_N FROM CP_CONTRASENA_PAGO
        WHERE ID_FACTURA_PROVEEDOR = p_id_factura AND ESTADO != 'ANULADA';
        RETURN L_N;
    END CONTRASENAS_ACTIVAS;

    -- Notas de credito/debito no anuladas aplicadas a la factura.
    FUNCTION NOTAS_ACTIVAS(p_id_factura IN NUMBER) RETURN NUMBER IS
        L_N NUMBER;
    BEGIN
        SELECT COUNT(*) INTO L_N FROM CP_FACTURA_PROVEEDOR
        WHERE ID_FACTURA_REFERENCIA = p_id_factura AND ESTADO != 'ANULADA';
        RETURN L_N;
    END NOTAS_ACTIVAS;

    -- Validaciones comunes de encabezado (crear y editar).
    PROCEDURE VALIDAR_CABECERA(
        p_id_factura IN NUMBER,
        p_id_proveedor IN NUMBER,
        p_tipo_documento IN VARCHAR2,
        p_numero_dte IN VARCHAR2,
        p_serie_dte IN VARCHAR2,
        p_fecha_emision IN DATE,
        p_fecha_documento IN DATE,
        p_fecha_vencimiento IN DATE,
        p_id_factura_referencia IN NUMBER
    ) IS
        L_N NUMBER;
        L_REF CP_FACTURA_PROVEEDOR%ROWTYPE;
    BEGIN
        -- Proveedor activo
        SELECT COUNT(*) INTO L_N FROM PROVEEDOR WHERE ID_PROVEEDOR = p_id_proveedor AND ESTADO = 'A';
        IF L_N = 0 THEN
            RAISE_APPLICATION_ERROR(-20120, 'El proveedor ' || p_id_proveedor || ' no existe o no esta activo.');
        END IF;

        -- Serie y numero de DTE obligatorios y sin duplicar por proveedor
        IF TRIM(p_serie_dte) IS NULL OR TRIM(p_numero_dte) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20121, 'La serie y el numero de DTE son obligatorios.');
        END IF;
        SELECT COUNT(*) INTO L_N FROM CP_FACTURA_PROVEEDOR
        WHERE ID_PROVEEDOR = p_id_proveedor
          AND UPPER(TRIM(SERIE_DTE)) = UPPER(TRIM(p_serie_dte))
          AND UPPER(TRIM(NUMERO_DTE)) = UPPER(TRIM(p_numero_dte))
          AND ESTADO != 'ANULADA'
          AND ID_FACTURA_PROVEEDOR != NVL(p_id_factura, -1);
        IF L_N > 0 THEN
            RAISE_APPLICATION_ERROR(-20122,
                'Ya existe un documento del mismo proveedor con serie ' || TRIM(p_serie_dte) ||
                ' y numero ' || TRIM(p_numero_dte) || '.');
        END IF;

        -- Fechas
        IF p_fecha_emision IS NULL OR p_fecha_documento IS NULL THEN
            RAISE_APPLICATION_ERROR(-20123, 'La fecha de emision y la fecha de documento son obligatorias.');
        END IF;
        IF TRUNC(p_fecha_emision) > TRUNC(SYSDATE) THEN
            RAISE_APPLICATION_ERROR(-20123, 'La fecha de emision no puede ser futura.');
        END IF;
        IF TRUNC(p_fecha_documento) < TRUNC(p_fecha_emision) THEN
            RAISE_APPLICATION_ERROR(-20123, 'La fecha de documento no puede ser anterior a la fecha de emision.');
        END IF;
        IF p_fecha_vencimiento IS NOT NULL AND TRUNC(p_fecha_vencimiento) < TRUNC(p_fecha_emision) THEN
            RAISE_APPLICATION_ERROR(-20123, 'La fecha de vencimiento no puede ser anterior a la fecha de emision.');
        END IF;

        -- Factura de referencia: obligatoria para notas, prohibida para facturas
        IF ES_NOTA(p_tipo_documento) THEN
            IF p_id_factura_referencia IS NULL THEN
                RAISE_APPLICATION_ERROR(-20124, 'Las notas de credito y debito deben indicar la factura a la que se aplican.');
            END IF;
            BEGIN
                SELECT * INTO L_REF FROM CP_FACTURA_PROVEEDOR WHERE ID_FACTURA_PROVEEDOR = p_id_factura_referencia;
            EXCEPTION
                WHEN NO_DATA_FOUND THEN
                    RAISE_APPLICATION_ERROR(-20124, 'La factura de referencia ' || p_id_factura_referencia || ' no existe.');
            END;
            IF ES_NOTA(L_REF.TIPO_DOCUMENTO) THEN
                RAISE_APPLICATION_ERROR(-20124, 'Una nota solo se puede aplicar a una FACTURA o FACTURA ESPECIAL.');
            END IF;
            IF L_REF.ESTADO = 'ANULADA' THEN
                RAISE_APPLICATION_ERROR(-20124, 'La factura de referencia ' || p_id_factura_referencia || ' esta ANULADA.');
            END IF;
            IF L_REF.ID_PROVEEDOR != p_id_proveedor THEN
                RAISE_APPLICATION_ERROR(-20124, 'La factura de referencia pertenece a otro proveedor.');
            END IF;
        ELSIF p_id_factura_referencia IS NOT NULL THEN
            RAISE_APPLICATION_ERROR(-20124, 'Solo las notas de credito y debito llevan factura de referencia.');
        END IF;
    END VALIDAR_CABECERA;

    PROCEDURE SP_RECALCULAR(p_id_factura IN NUMBER) IS
        L_F CP_FACTURA_PROVEEDOR%ROWTYPE;
        L_LINEAS NUMBER;
        L_TOTAL NUMBER;
        L_IVA NUMBER;
        L_ISR NUMBER;
        L_NC NUMBER;
        L_ND NUMBER;
        L_NETO NUMBER;
        L_PAGADO NUMBER;
        L_COMPROMETIDO NUMBER;
        L_SALDO NUMBER;
        L_ESTADO VARCHAR2(20);
    BEGIN
        LEER_FACTURA(p_id_factura, L_F);

        -- Total = suma de lineas (si una factura heredada no tiene lineas, se conserva su total)
        SELECT COUNT(*), NVL(SUM(SUBTOTAL), 0) INTO L_LINEAS, L_TOTAL
        FROM CP_FACTURA_PROVEEDOR_DETALLE WHERE ID_FACTURA_PROVEEDOR = p_id_factura;
        IF L_LINEAS = 0 THEN
            L_TOTAL := L_F.MONTO_TOTAL;
        END IF;

        SELECT NVL(SUM(CASE WHEN TIPO_RETENCION = 'IVA' THEN MONTO END), 0),
               NVL(SUM(CASE WHEN TIPO_RETENCION = 'ISR' THEN MONTO END), 0)
        INTO L_IVA, L_ISR
        FROM CP_RETENCION WHERE ID_FACTURA_PROVEEDOR = p_id_factura;

        IF ES_NOTA(L_F.TIPO_DOCUMENTO) THEN
            -- Las notas no se pagan: su efecto se refleja en la factura de referencia.
            L_SALDO := 0;
            L_ESTADO := CASE WHEN L_F.ESTADO = 'ANULADA' THEN 'ANULADA' ELSE 'APLICADA' END;
        ELSE
            SELECT NVL(SUM(CASE WHEN TIPO_DOCUMENTO = 'NOTA_CREDITO' THEN MONTO_TOTAL END), 0),
                   NVL(SUM(CASE WHEN TIPO_DOCUMENTO = 'NOTA_DEBITO' THEN MONTO_TOTAL END), 0)
            INTO L_NC, L_ND
            FROM CP_FACTURA_PROVEEDOR
            WHERE ID_FACTURA_REFERENCIA = p_id_factura AND ESTADO != 'ANULADA';

            SELECT NVL(SUM(CASE WHEN ESTADO IN ('EMITIDA', 'PAGADA') THEN MONTO END), 0),
                   NVL(SUM(CASE WHEN ESTADO = 'PENDIENTE' THEN MONTO END), 0)
            INTO L_PAGADO, L_COMPROMETIDO
            FROM CP_CONTRASENA_PAGO WHERE ID_FACTURA_PROVEEDOR = p_id_factura;

            L_NETO := L_TOTAL - L_IVA - L_ISR - L_NC + L_ND;
            L_SALDO := L_NETO - L_PAGADO;

            IF L_F.ESTADO = 'ANULADA' THEN
                L_SALDO := L_F.SALDO_PENDIENTE;
                L_ESTADO := 'ANULADA';
            ELSE
                IF L_SALDO < 0 THEN
                    RAISE_APPLICATION_ERROR(-20127,
                        'La operacion dejaria la factura ' || p_id_factura || ' con saldo negativo: neto a pagar ' ||
                        Q(L_NETO) || ' y ya se emitieron pagos por ' || Q(L_PAGADO) || '.');
                END IF;
                IF L_COMPROMETIDO > L_SALDO THEN
                    RAISE_APPLICATION_ERROR(-20128,
                        'La factura ' || p_id_factura || ' quedaria con saldo ' || Q(L_SALDO) ||
                        ', menor a sus contrasenas pendientes (' || Q(L_COMPROMETIDO) ||
                        '). Ajuste o anule esas contrasenas primero.');
                END IF;
                L_ESTADO := CASE
                                WHEN L_SALDO <= 0 THEN 'PAGADA'
                                WHEN L_PAGADO > 0 THEN 'PAGADA_PARCIAL'
                                ELSE 'PENDIENTE'
                            END;
            END IF;
        END IF;

        UPDATE CP_FACTURA_PROVEEDOR
        SET MONTO_TOTAL = L_TOTAL,
            MONTO_RETENCION_IVA = L_IVA,
            MONTO_RETENCION_ISR = L_ISR,
            SALDO_PENDIENTE = L_SALDO,
            ESTADO = L_ESTADO
        WHERE ID_FACTURA_PROVEEDOR = p_id_factura;

        -- Una nota afecta el saldo de la factura a la que se aplica.
        IF ES_NOTA(L_F.TIPO_DOCUMENTO) AND L_F.ID_FACTURA_REFERENCIA IS NOT NULL THEN
            SP_RECALCULAR(L_F.ID_FACTURA_REFERENCIA);
        END IF;
    END SP_RECALCULAR;

    PROCEDURE SP_LISTAR_FACTURAS(p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR
            SELECT * FROM VW_CP_FACTURA_PROVEEDOR ORDER BY ID_FACTURA_PROVEEDOR DESC;
    END SP_LISTAR_FACTURAS;

    PROCEDURE SP_OBTENER_FACTURA(
        p_id_factura IN NUMBER,
        p_cursor OUT SYS_REFCURSOR,
        p_cursor_detalle OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN p_cursor FOR
            SELECT * FROM VW_CP_FACTURA_PROVEEDOR WHERE ID_FACTURA_PROVEEDOR = p_id_factura;
        OPEN p_cursor_detalle FOR
            SELECT D.ID_FACTURA_PROV_DETALLE, D.ID_FACTURA_PROVEEDOR, D.ID_ARTICULO, D.DESCRIPCION,
                   D.CANTIDAD, D.PRECIO_UNITARIO, D.ID_UNIDAD_MEDIDA, D.SUBTOTAL,
                   U.DESCRIPCION AS UNIDAD_MEDIDA
            FROM CP_FACTURA_PROVEEDOR_DETALLE D
            LEFT JOIN CP_TIPO_UNIDAD_MEDIDA U ON U.ID_UNIDAD_MEDIDA = D.ID_UNIDAD_MEDIDA
            WHERE D.ID_FACTURA_PROVEEDOR = p_id_factura
            ORDER BY D.ID_FACTURA_PROV_DETALLE ASC;
    END SP_OBTENER_FACTURA;

    PROCEDURE SP_LISTAR_PROVEEDORES(p_cursor OUT SYS_REFCURSOR) IS
    BEGIN
        OPEN p_cursor FOR
            SELECT ID_PROVEEDOR, NIT, RAZON_SOCIAL, NOMBRE_COMERCIAL, DIAS_CREDITO
            FROM PROVEEDOR
            WHERE ESTADO = 'A'
            ORDER BY RAZON_SOCIAL ASC;
    END SP_LISTAR_PROVEEDORES;

    PROCEDURE SP_INSERTAR_FACTURA(
        p_id_proveedor IN NUMBER,
        p_tipo_documento IN VARCHAR2,
        p_numero_dte IN VARCHAR2,
        p_serie_dte IN VARCHAR2,
        p_fecha_emision IN DATE,
        p_fecha_documento IN DATE,
        p_fecha_vencimiento IN DATE,
        p_id_factura_referencia IN NUMBER,
        p_id_factura_out OUT NUMBER
    ) IS
        L_ESTADO_INICIAL VARCHAR2(20);
    BEGIN
        VALIDAR_CABECERA(NULL, p_id_proveedor, p_tipo_documento, p_numero_dte, p_serie_dte,
                         p_fecha_emision, p_fecha_documento, p_fecha_vencimiento, p_id_factura_referencia);

        -- (ES_NOTA es BOOLEAN y no se puede usar dentro de la sentencia SQL)
        L_ESTADO_INICIAL := CASE WHEN ES_NOTA(p_tipo_documento) THEN 'APLICADA' ELSE 'PENDIENTE' END;

        INSERT INTO CP_FACTURA_PROVEEDOR (
            ID_PROVEEDOR, TIPO_DOCUMENTO, NUMERO_DTE, SERIE_DTE,
            FECHA_EMISION, FECHA_DOCUMENTO, FECHA_VENCIMIENTO, MONTO_TOTAL,
            MONTO_RETENCION_IVA, MONTO_RETENCION_ISR, SALDO_PENDIENTE, ESTADO, ID_FACTURA_REFERENCIA
        ) VALUES (
            p_id_proveedor, p_tipo_documento, TRIM(p_numero_dte), TRIM(p_serie_dte),
            p_fecha_emision, p_fecha_documento, p_fecha_vencimiento, 0,
            0, 0, 0, L_ESTADO_INICIAL,
            p_id_factura_referencia
        ) RETURNING ID_FACTURA_PROVEEDOR INTO p_id_factura_out;
    END SP_INSERTAR_FACTURA;

    PROCEDURE SP_VALIDAR_TIENE_DETALLE(p_id_factura IN NUMBER) IS
        L_N NUMBER;
    BEGIN
        SELECT COUNT(*) INTO L_N FROM CP_FACTURA_PROVEEDOR_DETALLE WHERE ID_FACTURA_PROVEEDOR = p_id_factura;
        IF L_N = 0 THEN
            RAISE_APPLICATION_ERROR(-20126, 'El documento debe tener al menos una linea de detalle.');
        END IF;
    END SP_VALIDAR_TIENE_DETALLE;

    PROCEDURE SP_ACTUALIZAR_FACTURA(
        p_id_factura IN NUMBER,
        p_id_proveedor IN NUMBER,
        p_numero_dte IN VARCHAR2,
        p_serie_dte IN VARCHAR2,
        p_fecha_emision IN DATE,
        p_fecha_documento IN DATE,
        p_fecha_vencimiento IN DATE,
        p_id_factura_referencia IN NUMBER
    ) IS
        L_F CP_FACTURA_PROVEEDOR%ROWTYPE;
    BEGIN
        LEER_FACTURA(p_id_factura, L_F);
        IF L_F.ESTADO = 'ANULADA' THEN
            RAISE_APPLICATION_ERROR(-20126, 'No se puede editar un documento ANULADO.');
        END IF;
        IF NOT ES_NOTA(L_F.TIPO_DOCUMENTO) THEN
            IF L_F.ESTADO != 'PENDIENTE' OR CONTRASENAS_ACTIVAS(p_id_factura) > 0 THEN
                RAISE_APPLICATION_ERROR(-20126,
                    'Solo se puede editar una factura PENDIENTE y sin contrasenas de pago (esta esta ' || L_F.ESTADO ||
                    '). Anule primero sus contrasenas.');
            END IF;
            IF p_id_proveedor != L_F.ID_PROVEEDOR AND NOTAS_ACTIVAS(p_id_factura) > 0 THEN
                RAISE_APPLICATION_ERROR(-20126,
                    'No se puede cambiar el proveedor: la factura tiene notas de credito/debito aplicadas.');
            END IF;
        END IF;

        VALIDAR_CABECERA(p_id_factura, p_id_proveedor, L_F.TIPO_DOCUMENTO, p_numero_dte, p_serie_dte,
                         p_fecha_emision, p_fecha_documento, p_fecha_vencimiento, p_id_factura_referencia);

        UPDATE CP_FACTURA_PROVEEDOR
        SET ID_PROVEEDOR = p_id_proveedor,
            NUMERO_DTE = TRIM(p_numero_dte),
            SERIE_DTE = TRIM(p_serie_dte),
            FECHA_EMISION = p_fecha_emision,
            FECHA_DOCUMENTO = p_fecha_documento,
            FECHA_VENCIMIENTO = p_fecha_vencimiento,
            ID_FACTURA_REFERENCIA = p_id_factura_referencia
        WHERE ID_FACTURA_PROVEEDOR = p_id_factura;

        -- Si una nota cambia de factura, se recalculan la anterior y la nueva.
        IF ES_NOTA(L_F.TIPO_DOCUMENTO) AND NVL(L_F.ID_FACTURA_REFERENCIA, -1) != NVL(p_id_factura_referencia, -1) THEN
            IF L_F.ID_FACTURA_REFERENCIA IS NOT NULL THEN
                SP_RECALCULAR(L_F.ID_FACTURA_REFERENCIA);
            END IF;
            SP_RECALCULAR(p_id_factura);
        END IF;
    END SP_ACTUALIZAR_FACTURA;

    PROCEDURE SP_ANULAR_FACTURA(p_id_factura IN NUMBER, p_motivo IN VARCHAR2) IS
        L_F CP_FACTURA_PROVEEDOR%ROWTYPE;
    BEGIN
        IF p_motivo IS NULL OR TRIM(p_motivo) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20129, 'El motivo de anulacion es obligatorio.');
        END IF;
        LEER_FACTURA(p_id_factura, L_F);
        IF L_F.ESTADO = 'ANULADA' THEN
            RAISE_APPLICATION_ERROR(-20129, 'El documento ' || p_id_factura || ' ya esta ANULADO.');
        END IF;
        IF NOT ES_NOTA(L_F.TIPO_DOCUMENTO) THEN
            IF CONTRASENAS_ACTIVAS(p_id_factura) > 0 THEN
                RAISE_APPLICATION_ERROR(-20129,
                    'La factura tiene contrasenas de pago activas; anulelas primero (las EMITIDAS, anulando su cheque).');
            END IF;
            IF NOTAS_ACTIVAS(p_id_factura) > 0 THEN
                RAISE_APPLICATION_ERROR(-20129,
                    'La factura tiene notas de credito/debito aplicadas; anulelas primero.');
            END IF;
        END IF;

        -- El motivo queda registrado en NOTAS.
        UPDATE CP_FACTURA_PROVEEDOR
        SET ESTADO = 'ANULADA',
            NOTAS = SUBSTR(TRIM(p_motivo), 1, 300)
        WHERE ID_FACTURA_PROVEEDOR = p_id_factura;

        -- Anular una nota revierte su efecto en la factura de referencia.
        IF ES_NOTA(L_F.TIPO_DOCUMENTO) AND L_F.ID_FACTURA_REFERENCIA IS NOT NULL THEN
            SP_RECALCULAR(L_F.ID_FACTURA_REFERENCIA);
        END IF;
    END SP_ANULAR_FACTURA;

    PROCEDURE SP_VALIDAR_DETALLE_EDITABLE(p_id_factura IN NUMBER) IS
        L_F CP_FACTURA_PROVEEDOR%ROWTYPE;
    BEGIN
        LEER_FACTURA(p_id_factura, L_F);
        IF L_F.ESTADO = 'ANULADA' THEN
            RAISE_APPLICATION_ERROR(-20130, 'No se puede modificar el detalle de un documento ANULADO.');
        END IF;
        IF NOT ES_NOTA(L_F.TIPO_DOCUMENTO) AND CONTRASENAS_ACTIVAS(p_id_factura) > 0 THEN
            RAISE_APPLICATION_ERROR(-20130,
                'No se puede modificar el detalle: la factura tiene contrasenas de pago activas.');
        END IF;
    END SP_VALIDAR_DETALLE_EDITABLE;

END PKG_CP_FACTURA_PROVEEDOR;
