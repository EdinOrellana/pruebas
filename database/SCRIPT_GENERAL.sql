-- ============ Módulo de Nómina ============

-- SUCURSAL: Tiendas, oficinas centrales y bodegas centrales de la empresa.
CREATE TABLE SUCURSAL (
    ID_SUCURSAL NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CODIGO VARCHAR2(10) NOT NULL UNIQUE,
    NOMBRE VARCHAR2(100) NOT NULL,
    TIPO VARCHAR2(20) NOT NULL CHECK (TIPO IN ('TIENDA','OFICINA_CENTRAL','BODEGA_CENTRAL')),
    DIRECCION VARCHAR2(200),
    TELEFONO VARCHAR2(20),
    ESTADO CHAR(1) DEFAULT 'A' CHECK (ESTADO IN ('A','I')),
    CONSTRAINT PK_SUCURSAL PRIMARY KEY (ID_SUCURSAL)
);

-- DEPARTAMENTO: Áreas/departamentos organizacionales.
CREATE TABLE DEPARTAMENTO (
    ID_DEPARTAMENTO NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    ID_GERENTE NUMBER,
    CONSTRAINT PK_DEPARTAMENTO PRIMARY KEY (ID_DEPARTAMENTO)
);

-- PUESTO: Catálogo de puestos/cargos.
CREATE TABLE PUESTO (
    ID_PUESTO NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    ES_VENDEDOR CHAR(1) DEFAULT 'N' CHECK (ES_VENDEDOR IN ('S','N')),
    CONSTRAINT PK_PUESTO PRIMARY KEY (ID_PUESTO)
);

-- EMPLEADO: Todos los empleados de la empresa.
CREATE TABLE EMPLEADO (
    ID_EMPLEADO NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CODIGO_EMPLEADO VARCHAR2(15) NOT NULL UNIQUE,
    NOMBRES VARCHAR2(100) NOT NULL,
    APELLIDOS VARCHAR2(100) NOT NULL,
